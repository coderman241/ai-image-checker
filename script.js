function isImageFile(file) {
  // Some mobile browsers / formats (e.g. TIFF) report an empty MIME type,
  // so fall back to the file extension instead of rejecting the file.
  if (file.type && file.type.startsWith("image/")) return true;
  return /\.(jpe?g|png|gif|webp|bmp|tiff?|avif)$/i.test(file.name || "");
}

function onFileChosen(file) {
  clearError();
  if (!file || !isImageFile(file)) {
    showError("Please choose an image file.");
    checkButton.disabled = true;
    return;
  }
  selectedFile = file;
  // Hide any previous result until this image is checked.
  resultEl.hidden = true;
  emptyState.hidden = false;
  checkButton.disabled = true;
  if (selectedObjectUrl) {
    try { URL.revokeObjectURL(selectedObjectUrl); } catch { /* ignore */ }
    selectedObjectUrl = null;
  }
  // Use an object URL when available: far cheaper than a base64 data URL
  // for multi-megabyte photos on phones. Fall back to FileReader.
  if (typeof URL !== "undefined" && URL.createObjectURL) {
    try {
      selectedObjectUrl = URL.createObjectURL(file);
      selectedDataUrl = selectedObjectUrl;
      previewImg.src = selectedObjectUrl;
      fileInfo.textContent = `${file.name} — ${(file.size / 1024).toFixed(1)} KB — ${file.type || "image"}`;
      previewEl.hidden = false;
      // Do NOT enable "Check image" yet: imageStats needs naturalWidth /
      // naturalHeight, which are 0 until the preview image has decoded.
      // Enabling early gave bogus 1x1-image statistics.
      return;
    } catch { /* fall through to FileReader */ }
  }
  const reader = new FileReader();
  reader.onload = () => {
    selectedDataUrl = reader.result;
    previewImg.src = selectedDataUrl;
    fileInfo.textContent = `${file.name} — ${(file.size / 1024).toFixed(1)} KB — ${file.type || "image"}`;
    previewEl.hidden = false;
  };
  reader.onerror = () => {
    showError("Could not read this image file. Please try a different image.");
    checkButton.disabled = true;
  };
  reader.readAsDataURL(file);
}

