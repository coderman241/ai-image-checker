function findKeywords(text, keywords) {
  const lower = (text || "").toLowerCase();
  return keywords.filter((k) => lower.includes(k));
}

function decodeLatin1(bytes) {
  try {
    if (typeof TextDecoder !== "undefined") {
      return new TextDecoder("iso-8859-1").decode(bytes);
    }
  } catch { /* fall through */ }
  return Array.from(bytes, (b) => String.fromCharCode(b)).join("");
}

// ---------------------------------------------------------------------------
// Structured metadata parsing
// ---------------------------------------------------------------------------
// Chunk/segment parsing walks offsets and skips pixel data (PNG IDAT,
// JPEG scan data), so large files stay fast. Only the metadata text
// itself is decoded, plus a bounded whole-file fallback for generator /
// C2PA strings, which are usually in metadata near the start of a file.

function parsePngMetadata(bytes, out) {
  // PNG signature is 8 bytes; chunks are length(4) + type(4) + data + CRC(4).
  if (bytes.length < 8) return;
  let pos = 8;
  const chunkNames = new Set();
  while (pos + 8 <= bytes.length) {
    const len = new DataView(bytes.buffer, bytes.byteOffset + pos, 4).getUint32(0);
    const type = decodeLatin1(bytes.subarray(pos + 4, pos + 8));
    chunkNames.add(type);
    const dataStart = pos + 8;
    const dataEnd = Math.min(dataStart + len, bytes.length);
    if (type === "tEXt") {
      const raw = decodeLatin1(bytes.subarray(dataStart, dataEnd));
      const nul = raw.indexOf("\0");
      out.texts.push({
        key: nul >= 0 ? raw.slice(0, nul) : "",
        value: nul >= 0 ? raw.slice(nul + 1) : raw,
        source: "PNG text chunk",
      });
    } else if (type === "iTXt") {
      const raw = decodeLatin1(bytes.subarray(dataStart, dataEnd));
      const parts = raw.split("\0");
      out.texts.push({
        key: parts[0] || "",
        value: parts.slice(4).join("\0") || raw,
        source: "PNG text chunk",
      });
    } else if (type === "eXIf") {
      out.hasExif = true;
      parseExifTiff(bytes.subarray(dataStart, dataEnd), out);
    } else if (type === "jumb" || type === "c2pa" || type === "c2ma") {
      out.hasC2pa = true;
      out.texts.push({ key: type, value: "", source: "PNG C2PA/JUMBF chunk" });
    }
    // zTXt is deflate-compressed text; decoding is attempted by the
    // caller via scanMetadata only when DecompressionStream exists,
    // because it is async. Its presence alone still counts as metadata.
    if (type === "zTXt") out.hasTextChunks = true;
    if (type === "tEXt" || type === "iTXt") out.hasTextChunks = true;
    if (type === "IEND") break;
    if (!Number.isFinite(len) || len < 0) break;
    pos = dataEnd + 4; // skip CRC
    if (pos <= dataStart) break; // avoid an infinite loop on bad data
  }
  out.chunkNames = chunkNames;
  // A PNG with only IHDR / IDAT / IEND (plus optional gamma) carries
  // essentially no provenance at all.
  const nonPixel = [...chunkNames].filter((c) => !["IHDR", "IDAT", "IEND", "gAMA", "pHYs", "sRGB"].includes(c));
  out.pngMinimal = nonPixel.length === 0;
}

function readAscii(view, offset, length) {
  let s = "";
  for (let i = 0; i < length; i++) {
    const code = view.getUint8(offset + i);
    if (code === 0) break;
    s += String.fromCharCode(code);
  }
  return s;
}

function parseExifTiff(data, out) {
  // Minimal TIFF/EXIF parser: IFD0 Make/Model/Software plus a count of
  // detailed camera settings. Anything malformed is ignored, never fatal.
  try {
    if (data.length < 8) return;
    const view = new DataView(data.buffer, data.byteOffset, data.byteLength);
    const little = data[0] === 0x49 && data[1] === 0x49; // "II"
    if (!(data[0] === 0x49 || data[0] === 0x4d)) return;
    const ifdOffset = view.getUint32(4, little);
    if (ifdOffset + 2 > data.length) return;
    const entries = view.getUint16(ifdOffset, little);
    const detailTags = new Set([0x829a, 0x829d, 0x8827, 0x9003, 0x920a, 0x9209, 0xa002, 0xa003]);
    for (let i = 0; i < entries; i++) {
      const e = ifdOffset + 2 + i * 12;
      if (e + 12 > data.length) break;
      const tag = view.getUint16(e, little);
      const type = view.getUint16(e + 2, little);
      const count = view.getUint32(e + 4, little);
      const valueOffset = view.getUint32(e + 8, little);
      // ASCII (type 2): value is inline if <= 4 bytes, else an offset.
      if (type === 2 && count > 0) {
        const str = count <= 4
          ? readAscii(view, e + 8, count)
          : readAscii(view, valueOffset, count);
        if (tag === 0x010f) out.exifMake = str.trim();
        if (tag === 0x0110) out.exifModel = str.trim();
        if (tag === 0x0131) out.exifSoftware = str.trim();
      }
      if (detailTags.has(tag)) out.exifDetailCount = (out.exifDetailCount || 0) + 1;
      // EXIF sub-IFD (tag 0x8769) holds DateTimeOriginal etc.; count it
      // as detail if present, without recursing into it.
      if (tag === 0x8769) out.exifDetailCount = (out.exifDetailCount || 0) + 1;
    }
  } catch { /* malformed EXIF is not an error for the checker */ }
}

function parseJpegMetadata(bytes, out) {
  // JPEG: SOI (FFD8), then segments FFxx + length(2, includes length bytes).
  // Stop at SOS (FFDA) — scan data after it is not metadata.
  if (bytes.length < 4 || bytes[0] !== 0xff || bytes[1] !== 0xd8) return;
  let pos = 2;
  while (pos + 4 <= bytes.length) {
    if (bytes[pos] !== 0xff) break;
    const marker = bytes[pos + 1];
    if (marker === 0xda) break; // SOS: pixel data follows
    if (marker === 0xd9 || marker === 0x01 || (marker >= 0xd0 && marker <= 0xd7)) {
      pos += 2;
      continue;
    }
    const len = new DataView(bytes.buffer, bytes.byteOffset + pos + 2, 2).getUint16(0);
    if (len < 2) break;
    const dataStart = pos + 4;
    const dataEnd = Math.min(dataStart + len - 2, bytes.length);
    const segment = bytes.subarray(dataStart, dataEnd);
    const text = decodeLatin1(segment);
    if (marker === 0xe1) { // APP1: Exif or XMP
      if (text.startsWith("Exif\0\0")) {
        out.hasExif = true;
        // TIFF header starts after the 6-byte "Exif\0\0" prefix.
        parseExifTiff(segment.subarray(6), out);
      } else if (text.includes("http://ns.adobe.com/xap/1.0/")) {
        out.hasXmp = true;
        out.texts.push({ key: "XMP", value: text, source: "JPEG XMP" });
      } else if (text.includes("JUMBF") || text.includes("c2pa")) {
        out.hasC2pa = true;
      }
    } else if (marker === 0xe0 || marker === 0xe2 || marker === 0xed || marker === 0xee) {
      if (text.includes("http://ns.adobe.com/xap/1.0/")) {
        out.hasXmp = true;
        out.texts.push({ key: "XMP", value: text, source: "JPEG XMP" });
      }
    } else if (marker === 0xeb) { // APP11: C2PA/JUMBF in JPEG
      if (text.includes("JUMBF") || text.includes("c2pa")) out.hasC2pa = true;
    } else if (marker === 0xfe) { // COM comment
      out.texts.push({ key: "Comment", value: text, source: "JPEG comment" });
    }
    // Next segment is at marker(2) + length(len): dataEnd already equals
    // pos + len + 2, so it is the next segment start (not +2 further).
    pos = dataEnd;
    if (pos <= dataStart) break;
  }
}

function parseWebPMetadata(bytes, out) {
  // RIFF: "RIFF" + size(4) + "WEBP", then chunks: type(4) + size(4) + data.
  if (bytes.length < 12 || decodeLatin1(bytes.subarray(0, 4)) !== "RIFF") return;
  let pos = 12;
  while (pos + 8 <= bytes.length) {
    const type = decodeLatin1(bytes.subarray(pos, pos + 4));
    const size = new DataView(bytes.buffer, bytes.byteOffset + pos + 4, 4).getUint32(0, true);
    const dataStart = pos + 8;
    const dataEnd = Math.min(dataStart + size, bytes.length);
    const segment = bytes.subarray(dataStart, dataEnd);
    if (type === "EXIF") {
      out.hasExif = true;
      parseExifTiff(segment, out);
    } else if (type === "XMP ") {
      out.hasXmp = true;
      out.texts.push({ key: "XMP", value: decodeLatin1(segment), source: "WebP XMP" });
    }
    pos = dataEnd + (size % 2); // RIFF chunks are word-aligned
    if (pos <= dataStart) break;
  }
}

function parseGifMetadata(bytes, out) {
  // GIF comment (0x21 0xFE) and application (0x21 0xFF) extensions.
  for (let i = 0; i + 2 < bytes.length; i++) {
    if (bytes[i] === 0x21 && (bytes[i + 1] === 0xfe || bytes[i + 1] === 0xff)) {
      let j = i + 2;
      let text = "";
      while (j < bytes.length && bytes[j] !== 0) {
        const blockSize = bytes[j];
        text += decodeLatin1(bytes.subarray(j + 1, Math.min(j + 1 + blockSize, bytes.length)));
        j += 1 + blockSize;
      }
      if (text) out.texts.push({ key: "GIF extension", value: text, source: "GIF extension" });
    }
  }
}

// Scan PNG text chunks, JPEG EXIF/App segments, XMP, C2PA markers and
// software/camera strings, with structured sources preferred over a
// bare whole-file substring search.
async function scanMetadata(file) {
  const buffer = await file.arrayBuffer();
  const bytes = new Uint8Array(buffer);
  const out = {
    texts: [], hasExif: false, hasXmp: false, hasC2pa: false,
    hasTextChunks: false, pngMinimal: false, chunkNames: new Set(),
    exifMake: "", exifModel: "", exifSoftware: "", exifDetailCount: 0,
  };
  const isPng = bytes.length >= 8 && bytes[0] === 0x89 && bytes[1] === 0x50;
  const isJpeg = bytes.length >= 2 && bytes[0] === 0xff && bytes[1] === 0xd8;
  const isWebP = bytes.length >= 12 && decodeLatin1(bytes.subarray(8, 12)) === "WEBP";
  const isGif = bytes.length >= 6 && decodeLatin1(bytes.subarray(0, 6)).startsWith("GIF");

  if (isPng) parsePngMetadata(bytes, out);
  else if (isJpeg) parseJpegMetadata(bytes, out);
  else if (isWebP) parseWebPMetadata(bytes, out);
  else if (isGif) parseGifMetadata(bytes, out);

  // zTXt (compressed PNG text) — attempt a best-effort decompress when
  // the browser supports it; failure just means that text is skipped.
  if (isPng && typeof DecompressionStream !== "undefined") {
    try {
      let pos = 8;
      while (pos + 8 <= bytes.length) {
        const len = new DataView(bytes.buffer, bytes.byteOffset + pos, 4).getUint32(0);
        const type = decodeLatin1(bytes.subarray(pos + 4, pos + 8));
        const dataStart = pos + 8;
        const dataEnd = Math.min(dataStart + len, bytes.length);
        if (type === "zTXt") {
          const raw = bytes.subarray(dataStart, dataEnd);
          const nul = raw.indexOf(0);
          const compMethod = nul >= 0 ? raw[nul + 1] : 0;
          if (compMethod === 0) {
            const stream = new Blob([raw.subarray(nul + 2)]).stream()
              .pipeThrough(new DecompressionStream("deflate"));
            const decompressed = new Uint8Array(await new Response(stream).arrayBuffer());
            out.texts.push({
              key: decodeLatin1(raw.subarray(0, nul)),
              value: decodeLatin1(decompressed),
              source: "PNG compressed text chunk",
            });
          }
        }
        if (type === "IEND") break;
        pos = dataEnd + 4;
        if (pos <= dataStart) break;
      }
    } catch { /* compressed text is optional */ }
  }

  const metadataText = out.texts.map((t) => `${t.key} ${t.value}`).join("\n");
  const hasXmpText = metadataText.toLowerCase().includes("xmp") ||
    metadataText.includes("http://ns.adobe.com/xap/1.0/");
  if (hasXmpText) out.hasXmp = true;

  // Generator: structured metadata only. Do NOT scan raw file bytes:
  // compressed pixel data can contain short strings by chance, and a
  // generated apple PNG was falsely flagged as a DJI camera photo in
  // the Python version for exactly that reason.
  let generator = findKeywords(metadataText, GENERATOR_KEYWORDS);
  let generatorSource = generator.length ? "metadata" : "";
  // Diffusion-style parameters text is a strong generator signal even
  // without a brand name, e.g. a PNG "parameters" chunk from a render.
  const diffusionParams = DIFFUSION_PARAM_PATTERNS.filter((p) =>
    metadataText.toLowerCase().includes(p));
  if (!generator.length && diffusionParams.length >= 2) {
    generator = ["diffusion render parameters"];
    generatorSource = "metadata";
  }

  // C2PA: structured chunk/segment or metadata text only, for the
  // same reason as above — never raw compressed pixel data.
  let c2pa = out.hasC2pa || findKeywords(metadataText, C2PA_KEYWORDS).length > 0;

  // Camera: structured EXIF Make/Model first (most reliable), then a
  // metadata key/value pair, then a whole-file mention as a last resort.
  let camera = [];
  let cameraSource = "";
  const structuredCamera = [out.exifMake, out.exifModel].filter(Boolean);
  if (structuredCamera.length) {
    camera = findKeywords(structuredCamera.join(" "), CAMERA_MAKES);
    if (!camera.length) camera = structuredCamera; // an unknown make is still a camera
    cameraSource = "EXIF Make/Model";
  }
  if (!camera.length) {
    const metaCamera = findKeywords(metadataText, CAMERA_MAKES);
    // Only trust a metadata camera mention when it looks like a keyed
    // field (Make/Model/Camera) rather than a stray word in a caption.
    if (metaCamera.length && /(make|model|camera|tiff:make|tiff:model)/i.test(metadataText)) {
      camera = metaCamera;
      cameraSource = "metadata";
    }
  }
  if (!camera.length && out.exifMake) {
    camera = [out.exifMake];
    cameraSource = "EXIF Make/Model";
  }

  // Software: structured EXIF Software first, then metadata text.
  let software = [];
  if (out.exifSoftware) {
    software = findKeywords(out.exifSoftware, SOFTWARE_KEYWORDS);
    if (!software.length) software = [out.exifSoftware];
  }
  if (!software.length) software = findKeywords(metadataText, SOFTWARE_KEYWORDS);

  return {
    generator, generatorSource,
    c2pa,
    camera, cameraSource,
    software,
    exifDetailCount: out.exifDetailCount || 0,
    hasExif: out.hasExif,
    hasXmp: out.hasXmp,
    hasProvenance: out.hasExif || out.hasXmp || c2pa || out.hasTextChunks || out.texts.length > 0,
    pngMinimal: out.pngMinimal,
    format: isPng ? "PNG" : isJpeg ? "JPEG" : isWebP ? "WebP" : isGif ? "GIF" : "image",
  };
}

function imageStats(img) {
  // Draw a small copy to a canvas and measure smoothness, flat areas,
  // saturation and palette size. Weak evidence only — real photos can
  // be smooth, vivid and flat too. Downscaling to 256 px keeps this
  // fast on phones even for large photos.
  const maxSide = 256;
  const scale = Math.min(1, maxSide / Math.max(img.naturalWidth, img.naturalHeight));
  const w = Math.max(1, Math.round(img.naturalWidth * scale));
  const h = Math.max(1, Math.round(img.naturalHeight * scale));
  const canvas = document.createElement("canvas");
  canvas.width = w;
  canvas.height = h;
  const ctx = canvas.getContext("2d", { willReadFrequently: true });
  ctx.drawImage(img, 0, 0, w, h);
  const data = ctx.getImageData(0, 0, w, h).data;
  let diffSum = 0, diffCount = 0, satSum = 0, pxCount = 0;
  let edgeCount = 0, flatCount = 0, flatDiffSum = 0, flatDiffCount = 0;
  const colours = new Set();
  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      const i = (y * w + x) * 4;
      const r = data[i], g = data[i + 1], b = data[i + 2];
      const mx = Math.max(r, g, b), mn = Math.min(r, g, b);
      satSum += mx === 0 ? 0 : (mx - mn) / mx;
      pxCount++;
      colours.add(((r >> 4) << 8) | ((g >> 4) << 4) | (b >> 4));
      if (x + 1 < w) {
        const j = i + 4;
        const diff = (Math.abs(r - data[j]) + Math.abs(g - data[j + 1]) + Math.abs(b - data[j + 2])) / 3;
        diffSum += diff;
        diffCount++;
        if (diff > 25) edgeCount++;
        if (diff < 5) {
          flatCount++;
          flatDiffSum += diff;
          flatDiffCount++;
        }
      }
    }
  }
  return {
    meanNeighbourDiff: diffCount ? diffSum / diffCount : 0,
    meanSaturation: pxCount ? satSum / pxCount : 0,
    edgeDensity: diffCount ? edgeCount / diffCount : 0,
    flatFraction: diffCount ? flatCount / diffCount : 0,
    flatNoise: flatDiffCount ? flatDiffSum / flatDiffCount : 0,
    distinctQuantizedColours: colours.size,
  };
}

checkButton.addEventListener("click", async () => {
  if (!selectedFile) return;
  clearError();
  checkButton.disabled = true;
  checkButton.textContent = "Checking…";
  try {
    if (!previewImg.naturalWidth || !previewImg.naturalHeight) {
      throw new Error("preview image not loaded yet");
    }
    const meta = await scanMetadata(selectedFile);
    const stats = imageStats(previewImg);

    let score = 50;
    const reasons = [];

    if (meta.generator.length) {
      score += 35;
      const source = meta.generatorSource ? ` (${meta.generatorSource})` : "";
      reasons.push(`Heuristic: generator signal found in file data${source} (${meta.generator.join(", ")}).`);
    }
    if (meta.c2pa) {
      score += 10;
      reasons.push("Heuristic: file contains a C2PA / content-credentials marker (provenance metadata, not proof of AI generation on its own).");
    }
    // Mutually exclusive provenance chain: camera, else software-only,
    // else no camera data — matching the Python version.
    if (meta.camera.length) {
      score -= 25;
      const source = meta.cameraSource ? ` in ${meta.cameraSource}` : "";
      reasons.push(`Heuristic: camera make found${source} (${meta.camera.join(", ")}).`);
      if (meta.exifDetailCount >= 2) {
        score -= 5;
        reasons.push("Heuristic: detailed camera settings found in EXIF (exposure / ISO / focal length / date), which is more consistent with a camera photo.");
      }
    } else if (meta.software.length) {
      score += 10;
      reasons.push(`Heuristic: software-only provenance (${meta.software.join(", ")}), no camera make.`);
    } else {
      score += 5;
      reasons.push(`Heuristic (weak): no camera make found in file data${meta.hasProvenance ? "" : " and no EXIF, XMP or other provenance blocks were found"}.`);
    }
    if (meta.pngMinimal) {
      score += 5;
      reasons.push("Heuristic (weak): PNG carries almost no metadata chunks, so there is no provenance to check.");
    }

    // Weak image clues, each +5, total capped at +15. Textured images
    // pull the other way (-5) and are not part of that cap.
    let weakImage = 0;
    const addWeakImage = (reason) => {
      if (weakImage < 15) {
        weakImage += 5;
        score += 5;
        reasons.push(reason);
      }
    };
    if (stats.meanNeighbourDiff < 4) {
      addWeakImage("Heuristic (weak): image areas are very smooth / low-noise.");
    } else if (stats.meanNeighbourDiff > 25) {
      score -= 5;
      reasons.push("Heuristic (weak): relatively textured / noisy image.");
    }
    if (stats.meanSaturation > 0.55) {
      addWeakImage("Heuristic (weak): unusually high average saturation.");
    }
    if (stats.flatFraction > 0.45) {
      addWeakImage("Heuristic (weak): large flat / uniform areas with little detail.");
    } else if (stats.flatFraction > 0.25 && stats.flatNoise < 2) {
      // Clean flat areas without being globally smooth: unnaturally
      // clean in the flat parts, while the rest of the image has detail.
      addWeakImage("Heuristic (weak): flat areas are unnaturally clean / noise-free.");
    }
    if (stats.distinctQuantizedColours < 1200 && stats.distinctQuantizedColours > 0) {
      addWeakImage("Heuristic (weak): limited colour palette for a photo of this size.");
    }
    if (!reasons.length) reasons.push("Heuristic: no strong metadata or image clues found.");

    // Guarantee: without a generator signal, weak clues alone can never
    // reach "likely AI-generated".
    if (!meta.generator.length) {
      score = Math.min(score, 74);
    }
    score = Math.max(0, Math.min(100, Math.round(score)));
    let verdict, cls;
    if (score >= 75) { verdict = "likely AI-generated"; cls = "ai"; }
    else if (score <= 35) { verdict = "likely real / camera photo"; cls = "real"; }
    else { verdict = "uncertain"; cls = "uncertain"; }

    verdictEl.textContent = verdict;
    verdictEl.className = `verdict ${cls}`;
    scoreEl.textContent = String(score);
    scoreFill.style.width = `${score}%`;
    reasonsEl.innerHTML = "";
    reasons.forEach((r) => {
      const li = document.createElement("li");
      li.textContent = r;
      reasonsEl.appendChild(li);
    });
    emptyState.hidden = true;
    resultEl.hidden = false;
  } catch (err) {
    showError("Could not check this image. Please try a different image file.");
  } finally {
    // Only re-enable if the preview is actually loaded; otherwise the
    // previewImg.onload handler will enable it once decoding finishes.
    checkButton.disabled = !previewImg.naturalWidth;
    checkButton.textContent = "Check image";
  }
});
