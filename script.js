// AI Image Checker — client-side only, no uploads, no network calls.
// Mirrors the Python version's scoring: start at 50, thresholds 75 / 35.
// Every reason is labelled as a heuristic, not proof.
//
// Scoring rules, in brief:
//   * A strong generator / provenance signal is +35 (generator keyword,
//     Stable-Diffusion-style "parameters" text, etc.).
//   * C2PA / content-credentials is +10: it is provenance metadata,
//     not proof of AI generation on its own.
//   * A camera make in structured EXIF/metadata is -25, with -5 more
//     if detailed camera settings (exposure, ISO, focal length, …) are
//     present. Software-only provenance is +10, no camera data is +5.
//   * Image clues (smoothness, flat areas, saturation, palette) are
//     weak: each is +5, their total is capped at +15, and — crucially —
//     if no generator signal is present the final score is capped at 74.
//     Weak clues together therefore stay in "uncertain" and can never
//     alone reach "likely AI-generated".

