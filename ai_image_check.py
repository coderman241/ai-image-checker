def parse_png_chunks(data: bytes) -> list[tuple[str, bytes]]:
    """Return [(chunk_type, body)] for a PNG, or [] on bad input."""
    chunks: list[tuple[str, bytes]] = []
    if not data.startswith(b"\x89PNG\r\n\x1a\n"):
        return chunks
    pos = 8
    try:
        while pos + 8 <= len(data):
            length = struct.unpack(">I", data[pos : pos + 4])[0]
            chunk_type = data[pos + 4 : pos + 8].decode("ascii", "ignore")
            start = pos + 8
            end = start + length
            if end > len(data):
                break
            chunks.append((chunk_type, data[start:end]))
            if chunk_type == "IEND":
                break
            pos = end + 4  # skip CRC
    except Exception:
        return chunks
    return chunks


def extract_png_text_chunks(data: bytes) -> list[str]:
    """Return decoded PNG tEXt / iTXt / zTXt chunk contents, if any.

    Returns an empty list for non-PNG data or on any parse problem;
    a malformed PNG should not crash the checker. Keyword and text
    are both kept, so e.g. ("Software", "Midjourney") is searchable
    as "software midjourney".
    """
    chunks: list[str] = []
    for chunk_type, body in parse_png_chunks(data):
        try:
            if chunk_type == "tEXt":
                chunks.append(body.decode("utf-8", "ignore"))
            elif chunk_type == "iTXt":
                # keyword NUL compression-flag compression-method
                # language-tag NUL translated-keyword NUL text
                parts = body.split(b"\x00")
                if parts:
                    chunks.append(b" ".join(parts).decode("utf-8", "ignore"))
            elif chunk_type == "zTXt":
                nul = body.index(b"\x00")
                chunks.append(
                    zlib.decompress(body[nul + 2 :]).decode("utf-8", "ignore")
                )
        except Exception:
            continue
    return chunks


def parse_tiff_ifd(data: bytes, offset: int, endian: str) -> dict[int, str]:
    """Parse one TIFF IFD at ``offset``; return {tag: ascii_value}.

    Only ASCII (type 2) tags are returned, which covers Make, Model,
    Software, Artist, Copyright, DateTime and XMP-adjacent fields.
    Any malformed structure returns what was parsed so far, or {}.
    """
    tags: dict[int, str] = {}
    try:
        if offset + 2 > len(data):
            return tags
        count = struct.unpack(endian + "H", data[offset : offset + 2])[0]
        for i in range(count):
            entry = offset + 2 + i * 12
            if entry + 12 > len(data):
                break
            tag, typ, num = struct.unpack(endian + "HHI", data[entry : entry + 8])
            if typ != 2 or num == 0:  # ASCII only
                continue
            value_bytes = data[entry + 8 : entry + 12]
            if num > 4:
                ptr = struct.unpack(endian + "I", value_bytes)[0]
                if ptr + num > len(data):
                    continue
                raw = data[ptr : ptr + num]
            else:
                raw = value_bytes[:num]
            text = raw.split(b"\x00", 1)[0].decode("utf-8", "ignore").strip()
            if text:
                tags[tag] = text
    except Exception:
        pass
    return tags


def parse_exif_tiff(data: bytes) -> dict[int, str]:
    """Parse a TIFF/EXIF blob (JPEG APP1 Exif, PNG eXIf, TIFF file)."""
    if len(data) < 8:
        return {}
    header = data[:2]
    if header == b"II":
        endian = "<"
    elif header == b"MM":
        endian = ">"
    else:
        return {}
    try:
        if struct.unpack(endian + "H", data[2:4])[0] != 42:
            return {}
        ifd_offset = struct.unpack(endian + "I", data[4:8])[0]
    except Exception:
        return {}
    return parse_tiff_ifd(data, ifd_offset, endian)


def parse_jpeg_segments(data: bytes) -> dict:
    """Parse JPEG markers; return exif tags, XMP text, comments, flags."""
    exif_tags: dict[int, str] = {}
    xmp_texts: list[str] = []
    comments: list[str] = []
    has_jumbf = False
    segments: list[str] = []
    if not data.startswith(b"\xff\xd8"):
        return {
            "exif_tags": exif_tags,
            "xmp_texts": xmp_texts,
            "comments": comments,
            "has_jumbf": has_jumbf,
            "segments": segments,
        }
    pos = 2
    try:
        while pos + 4 <= len(data):
            if data[pos] != 0xFF:
                break
            marker = data[pos + 1]
            segments.append(f"FF{marker:02X}")
            if marker == 0xD9:  # EOI
                break
            if marker == 0xDA:  # SOS: image data follows, stop scanning
                break
            if marker in (0x01,) or 0xD0 <= marker <= 0xD7:
                pos += 2
                continue
            length = struct.unpack(">H", data[pos + 2 : pos + 4])[0]
            body = data[pos + 4 : pos + 2 + length]
            if marker == 0xE1 and body.startswith(b"Exif\x00\x00"):
                exif_tags.update(parse_exif_tiff(body[6:]))
            elif marker == 0xE1 and b"http://ns.adobe.com/xap/1.0/" in body:
                xmp_texts.append(body.decode("utf-8", "ignore"))
            elif marker == 0xEB:  # APP11, used by JUMBF / C2PA
                if b"JUMBF" in body or b"jumbf" in body:
                    has_jumbf = True
            elif marker == 0xFE:  # COM comment
                comments.append(body.decode("utf-8", "ignore"))
            pos += 2 + length
    except Exception:
        pass
    return {
        "exif_tags": exif_tags,
        "xmp_texts": xmp_texts,
        "comments": comments,
        "has_jumbf": has_jumbf,
        "segments": segments,
    }


def parse_webp_chunks(data: bytes) -> dict:
    """Parse WebP RIFF chunks; return exif tags, XMP text, chunk names."""
    exif_tags: dict[int, str] = {}
    xmp_texts: list[str] = []
    chunks: list[str] = []
    if not (data[:4] == b"RIFF" and data[8:12] == b"WEBP"):
        return {"exif_tags": exif_tags, "xmp_texts": xmp_texts, "chunks": chunks}
    pos = 12
    try:
        while pos + 8 <= len(data):
            chunk_id = data[pos : pos + 4].decode("ascii", "ignore")
            size = struct.unpack("<I", data[pos + 4 : pos + 8])[0]
            body = data[pos + 8 : pos + 8 + size]
            chunks.append(chunk_id)
            if chunk_id == "EXIF":
                exif_tags.update(parse_exif_tiff(body))
            elif chunk_id == "XMP ":
                xmp_texts.append(body.decode("utf-8", "ignore"))
            pos += 8 + size + (size % 2)
    except Exception:
        pass
    return {"exif_tags": exif_tags, "xmp_texts": xmp_texts, "chunks": chunks}


def extract_xmp_creator_tools(xmp_texts: list[str]) -> list[str]:
    """Pull CreatorTool / creator-tool values out of XMP packets."""
    tools: list[str] = []
    pattern = re.compile(
        r'(?:xmp:CreatorTool|CreatorTool|creator-tool)\s*=\s*"([^"]+)"',
        re.IGNORECASE,
    )
    for text in xmp_texts:
        for match in pattern.findall(text):
            tools.append(match.strip())
    return tools


def analyse_metadata(data: bytes, fmt: str) -> dict:
    """Heuristic 1 & 2: metadata and file/format clues.

    Structured parsing is preferred; a raw printable-text scan is
    kept as a fallback so keywords in comments, GIF text, or
    unparsed chunks are not missed. Nothing here is treated as proof.
    Returns a dict that keeps every key older versions returned, plus
    new parsed_* / xmp_* keys (extra keys do not change the CLI or
    JSON shape for existing fields).
    """
    raw_text = extract_printable_text(data)
    png_chunks = parse_png_chunks(data) if fmt == "PNG" else []
    png_text_list = extract_png_text_chunks(data) if fmt == "PNG" else []
    png_text = " ".join(png_text_list).lower()

    exif_tags: dict[int, str] = {}
    xmp_texts: list[str] = []
    comments: list[str] = []
    has_jumbf = False
    jpeg_segments: list[str] = []
    webp_chunks: list[str] = []

    if fmt == "JPEG":
        parsed = parse_jpeg_segments(data)
        exif_tags = parsed["exif_tags"]
        xmp_texts = parsed["xmp_texts"]
        comments = parsed["comments"]
        has_jumbf = parsed["has_jumbf"]
        jpeg_segments = parsed["segments"]
    elif fmt == "PNG":
        for chunk_type, body in png_chunks:
            if chunk_type == "eXIf":
                exif_tags.update(parse_exif_tiff(body))
            elif chunk_type == "iTXt" and b"xml" in body.lower():
                xmp_texts.append(body.decode("utf-8", "ignore"))
    elif fmt == "WEBP":
        parsed = parse_webp_chunks(data)
        exif_tags = parsed["exif_tags"]
        xmp_texts = parsed["xmp_texts"]
        webp_chunks = parsed["chunks"]
    elif fmt == "TIFF":
        exif_tags = parse_exif_tiff(data)

    # Structured text: EXIF Make/Model/Software/Artist, XMP, comments,
    # PNG text chunks. This is more trustworthy than the raw scan
    # (which can match words inside compressed pixel data), so it is
    # reported separately and used first in scoring.
    structured_parts: list[str] = []
    for tag in (0x010F, 0x0110, 0x0131, 0x013B, 0x8298):  # Make, Model, Software, Artist, Copyright
        if tag in exif_tags:
            structured_parts.append(exif_tags[tag])
    structured_parts.extend(xmp_texts)
    structured_parts.extend(extract_xmp_creator_tools(xmp_texts))
    structured_parts.extend(comments)
    structured_parts.append(png_text)
    structured_text = " ".join(structured_parts).lower()

    # IMPORTANT: do NOT search raw file bytes for keywords. Compressed
    # pixel data (e.g. PNG IDAT) can contain short strings by chance —
    # a generated apple PNG was falsely flagged as a DJI camera photo
    # because "dji" occurred once inside compressed pixel data.
    # Only structured metadata (EXIF, XMP, comments, PNG text chunks)
    # is trusted for generator / camera / software signals.
    # raw_text is kept only as a diagnostic, not for scoring.
    searchable = structured_text
    generator_found = _find_keywords(searchable, GENERATOR_KEYWORDS)
    parsed_generator = _find_keywords(structured_text, GENERATOR_KEYWORDS)
    camera_found = _find_keywords(searchable, CAMERA_MAKES)
    parsed_camera = _find_keywords(structured_text, CAMERA_MAKES)
    software_found = _find_keywords(searchable, SOFTWARE_KEYWORDS)
    parsed_software = _find_keywords(structured_text, SOFTWARE_KEYWORDS)

    # C2PA: a provenance standard, not a generator name. A real
    # manifest needs a JUMBF box / c2pa claim; a bare mention of the
    # word in text is only a marker, scored the same weak way.
    has_c2pa = (
        "c2pa" in searchable
        or "content credentials" in searchable
        or "jumbf" in searchable
        or has_jumbf
    )
    c2pa_manifest = has_jumbf or ("c2pa" in structured_text and "claim" in structured_text)

    has_exif_marker = bool(exif_tags) or (fmt == "PNG" and b"eXIf" in data)
    # A parsed Make/Model/DateTime is real EXIF, not just the word "exif".
    exif_tag_names = {
        0x010F: "Make",
        0x0110: "Model",
        0x0131: "Software",
        0x013B: "Artist",
        0x0132: "DateTime",
        0x8298: "Copyright",
        0x9000: "ExifVersion",
        0xA002: "PixelXDimension",
    }
    exif_tags_found = sorted({exif_tag_names.get(t, f"tag_{t:04X}") for t in exif_tags})

    return {
        "format": fmt,
        "generator_keywords": generator_found,
        "parsed_generator_keywords": parsed_generator,
        "camera_makes": camera_found,
        "parsed_camera_makes": parsed_camera,
        "software_keywords": software_found,
        "parsed_software_keywords": parsed_software,
        "has_c2pa_marker": has_c2pa,
        "c2pa_manifest_present": c2pa_manifest,
        "has_exif_marker": has_exif_marker,
        "has_parsed_exif": bool(exif_tags),
        "exif_tags_found": exif_tags_found,
        "xmp_present": bool(xmp_texts),
        "xmp_creator_tools": extract_xmp_creator_tools(xmp_texts),
        "png_text_chunks_found": len(png_text_list) if fmt == "PNG" else 0,
        "jpeg_segments_found": len(jpeg_segments) if fmt == "JPEG" else 0,
        "webp_chunks_found": len(webp_chunks) if fmt == "WEBP" else 0,
    }


def analyse_image_statistics(path: Path) -> dict | None:
    """Heuristic 3: simple image statistics, Pillow only.

    Lightweight and deliberately weak: a small thumbnail is used, and
    only a few summaries are computed.

    * mean neighbour difference: texture/noise proxy. Very low values
      mean large smooth areas, which can occur in AI images but also
      in real photos of sky, walls, or out-of-focus areas.
    * neighbour-difference spread: how uniform the texture is.
    * mean saturation: unusually high saturation can occur in AI
      images, but also in edited or vivid real photos.
    * unique-colour ratio: a very flat / posterised palette is a
      weak clue, and also occurs in logos and illustrations.

    Returns None when Pillow is unavailable or the image cannot be
    opened (the caller then reports that statistics were skipped).
    """
    if not PILLOW_AVAILABLE or Image is None:
        return None
    try:
        with Image.open(path) as img:
            img = img.convert("RGB")
            thumb = img.copy()
            thumb.thumbnail((256, 256))
            width, height = thumb.size
            if width < 2 or height < 2:
                return None
            pixels = list(thumb.getdata())

            def pixel(x: int, y: int) -> tuple[int, int, int]:
                return pixels[y * width + x]

            neighbour_diffs: list[float] = []
            saturations: list[float] = []
            for y in range(height):
                for x in range(width):
                    r, g, b = pixel(x, y)
                    mx, mn = max(r, g, b), min(r, g, b)
                    saturations.append((mx - mn) / mx if mx else 0.0)
                    if x + 1 < width:
                        r2, g2, b2 = pixel(x + 1, y)
                        neighbour_diffs.append(
                            (abs(r - r2) + abs(g - g2) + abs(b - b2)) / 3.0
                        )
            if not neighbour_diffs:
                return None
            mean_diff = sum(neighbour_diffs) / len(neighbour_diffs)
            variance = sum((d - mean_diff) ** 2 for d in neighbour_diffs) / len(neighbour_diffs)
            unique_ratio = len(set(pixels)) / max(1, len(pixels))
            return {
                "mean_neighbour_difference": round(mean_diff, 2),
                "neighbour_difference_stddev": round(math.sqrt(variance), 2),
                "mean_saturation": round(sum(saturations) / len(saturations), 3),
                "unique_colour_ratio": round(unique_ratio, 4),
                "thumbnail_size": [width, height],
            }
    except Exception:
        return None


def score_and_reasons(metadata: dict, stats: dict | None) -> tuple[int, list[str]]:
    """Combine heuristics into a 0-100 score and labelled reasons.

    Starts at 50 (uncertain). Strong signals (generator name,
    camera make) move it directly. Weak signals are accumulated
    separately and capped at WEAK_SIGNAL_CAP, so weak evidence alone
    can never reach "likely AI-generated". Every reason is labelled
    as a heuristic, not proof.
    """
    score = 50
    weak_score = 0
    reasons: list[str] = []

    def add_weak(points: int, reason: str) -> None:
        nonlocal weak_score
        weak_score += points
        reasons.append(reason)

    # -- Strong: generator name, parsed or raw -------------------------
    if metadata.get("generator_keywords"):
        score += 35
        source = "structured metadata" if metadata.get("parsed_generator_keywords") else "file data"
        reasons.append(
            "heuristic: metadata mentions an AI generator "
            f"({', '.join(metadata['generator_keywords'])}) in {source}"
        )
    # -- Provenance: C2PA is NOT a generator name ----------------------
    if metadata.get("has_c2pa_marker"):
        score += 10
        reasons.append(
            "heuristic: file contains a C2PA / content-credentials marker "
            "(provenance metadata, not proof of AI generation on its own)"
        )
    # -- Strong: camera make -------------------------------------------
    if metadata.get("camera_makes"):
        score -= 25
        source = "structured EXIF" if metadata.get("parsed_camera_makes") else "file data"
        reasons.append(
            "heuristic: metadata mentions a camera make "
            f"({', '.join(metadata['camera_makes'])}) in {source}"
        )
        if metadata.get("parsed_camera_makes") and metadata.get("has_parsed_exif"):
            # Parsed Make (and usually Model) is the strongest real-photo
            # signal available here, but still not proof: EXIF can be faked.
            score -= 5
            reasons.append(
                "heuristic: camera make found in parsed EXIF "
                f"({', '.join(metadata['parsed_camera_makes'])})"
            )
    elif metadata.get("software_keywords"):
        add_weak(
            10,
            "heuristic: software-only provenance "
            f"({', '.join(metadata['software_keywords'])}) with no camera make found",
        )
    elif not metadata.get("has_exif_marker"):
        add_weak(
            5,
            "heuristic: no camera EXIF marker found "
            "(weak: many real shared photos also have no EXIF)",
        )

    if metadata.get("xmp_present") and metadata.get("xmp_creator_tools"):
        reasons.append(
            "heuristic: XMP CreatorTool present "
            f"({', '.join(metadata['xmp_creator_tools'])})"
        )

    # -- Weak: image statistics, capped --------------------------------
    if stats is None:
        if not PILLOW_AVAILABLE:
            reasons.append(
                "heuristic: image statistics skipped (Pillow not installed); "
                "verdict is based on metadata/format clues only"
            )
        else:
            reasons.append(
                "heuristic: image statistics skipped "
                "(image could not be analysed); verdict is based on "
                "metadata/format clues only"
            )
    else:
        diff = stats["mean_neighbour_difference"]
        sat = stats["mean_saturation"]
        if diff < 4.0:
            add_weak(
                10,
                "heuristic: very smooth / low-noise areas "
                f"(mean neighbour difference {diff}; weak evidence, "
                "real photos of sky or plain surfaces look similar)",
            )
        elif diff > 25.0:
            add_weak(
                -5,
                "heuristic: relatively textured / noisy image "
                f"(mean neighbour difference {diff}; weak evidence)",
            )
        # Uniform texture and a flat palette are the *same* evidence as
        # smoothness for a solid-colour image, so they must not stack
        # on top of the smooth bonus: that would double-count one
        # clue and let a solid grey camera image miss the "likely
        # real" threshold. They only apply when the image is not
        # already scored as very smooth.
        if diff >= 4.0:
            stddev = stats.get("neighbour_difference_stddev")
            if stddev is not None and diff < 10.0 and stddev < 2.0:
                add_weak(
                    5,
                    "heuristic: unusually uniform texture "
                    f"(neighbour-difference spread {stddev}; weak evidence)",
                )
            unique = stats.get("unique_colour_ratio")
            if unique is not None and unique < 0.05:
                add_weak(
                    5,
                    "heuristic: very flat / limited colour palette "
                    f"(unique colours {unique} of pixels; weak evidence, "
                    "logos and illustrations look similar)",
                )
        if sat > 0.55:
            add_weak(
                5,
                "heuristic: unusually high average saturation "
                f"({sat}; weak evidence, edited real photos can also be vivid)",
            )

    # Apply the weak-signal cap, preserving its sign.
    capped_weak = max(-WEAK_SIGNAL_CAP, min(WEAK_SIGNAL_CAP, weak_score))
    if capped_weak != weak_score:
        reasons.append(
            "heuristic: weak signals capped at "
            f"{WEAK_SIGNAL_CAP} points, so weak evidence alone cannot "
            "reach 'likely AI-generated'"
        )
    score += capped_weak

    score = max(0, min(100, score))
    if not reasons:
        reasons.append("heuristic: no useful metadata or statistics signal found")
    return score, reasons


def verdict_for_score(score: int) -> str:
    """Map a 0-100 score to a plain-language, non-absolute verdict."""
    if score >= 75:
        return "likely AI-generated"
    if score <= 35:
        return "likely real / camera photo"
    return "uncertain"


def check_image(path: Path) -> dict:
    """Run all heuristics for one file and return a result dict.

    Raises ValueError with a clear, user-facing message (not a
    traceback) for missing files, non-images, and unsupported formats.
    Large files are handled by scanning only the first
    METADATA_SCAN_LIMIT bytes for metadata; Pillow still opens the
    file by path for statistics, so results are not truncated.
    """
    if not path.exists():
        raise ValueError(f"file not found: {path}")
    if not path.is_file():
        raise ValueError(f"not a regular file: {path}")

    try:
        file_size = path.stat().st_size
    except OSError as exc:
        raise ValueError(f"could not read file: {path} ({exc})") from exc

    if file_size == 0:
        raise ValueError(f"file is empty: {path}")

    try:
        with path.open("rb") as handle:
            data = handle.read(METADATA_SCAN_LIMIT + 1)
    except OSError as exc:
        raise ValueError(f"could not read file: {path} ({exc})") from exc

    metadata_scan_truncated = len(data) > METADATA_SCAN_LIMIT
    scan_data = data[:METADATA_SCAN_LIMIT]

    fmt = detect_format(scan_data)
    if fmt is None:
        raise ValueError(
            f"not a supported image file: {path} "
            "(supported: JPEG, PNG, GIF, WebP, BMP, TIFF)"
        )

    metadata = analyse_metadata(scan_data, fmt)
    metadata["metadata_scan_truncated"] = metadata_scan_truncated
    stats = analyse_image_statistics(path)
    score, reasons = score_and_reasons(metadata, stats)

    return {
        "path": str(path),
        "format": fmt,
        "verdict": verdict_for_score(score),
        "score": score,
        "reasons": reasons,
        "metadata": metadata,
        "image_statistics": stats,
        "pillow_available": PILLOW_AVAILABLE,
        "file_size_bytes": file_size,
        "note": (
            "Heuristic result only, not proof. "
            "Metadata can be stripped or faked, and image statistics "
            "are weak evidence."
        ),
    }


def build_parser() -> argparse.ArgumentParser:
    """Build the CLI parser, including the limitations in --help."""
    parser = argparse.ArgumentParser(
        description=(
            "Check an image for heuristic signs of AI generation. "
            "This is NOT a definitive AI detector."
        ),
        epilog=(
            "Limitations: this program uses metadata, format clues, and "
            "simple image statistics only. Metadata can be stripped, "
            "edited, or faked, and smooth or vivid areas also occur in "
            "real photos. Treat every verdict as a labelled heuristic "
            "guess, not certainty, and do not use it as sole proof "
            "about an image's origin. No network calls are made."
        ),
    )
    parser.add_argument(
        "image_path",
        help="Path to an image file (JPEG, PNG, GIF, WebP, BMP, or TIFF).",
    )
    parser.add_argument(
        "--json",
        action="store_true",
        help="Print the result as JSON instead of human-readable text.",
    )
    return parser


def print_text_result(result: dict) -> None:
    """Print a short, human-readable result."""
    print(f"File:    {result['path']}")
    print(f"Format:  {result['format']}")
    print(f"Verdict: {result['verdict']}")
    print(f"Score:   {result['score']} / 100 (0 = likely real, 100 = likely AI)")
    print("Reasons:")
    for reason in result["reasons"]:
        print(f"  - {reason}")
    print(f"Note:    {result['note']}")


def main(argv: list[str] | None = None) -> int:
    """CLI entry point. Returns 0 on success, 2 on a handled error."""
    parser = build_parser()
    args = parser.parse_args(argv)

    try:
        result = check_image(Path(args.image_path))
    except ValueError as exc:
        print(f"Error: {exc}", file=sys.stderr)
        return 2

    if args.json:
        print(json.dumps(result, indent=2))
    else:
        print_text_result(result)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
