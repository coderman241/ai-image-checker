#!/usr/bin/env python3
"""Simple, heuristic AI-image checker.

This program does NOT prove whether an image is AI-generated or real.
It looks at a few lightweight clues -- file metadata, format/provenance
signs, and (optionally) simple image statistics -- and returns an
honest, labelled verdict:

    "likely AI-generated"
    "likely real / camera photo"
    "uncertain"

plus a 0-100 score and brief reasons for that score.

Score meaning
-------------
0   = most consistent with a real / camera photo
100 = most consistent with an AI-generated image
50  = no useful signal either way

Verdict thresholds (see ``verdict_for_score``):
    score >= 75  -> likely AI-generated
    score <= 35  -> likely real / camera photo
    otherwise    -> uncertain

The higher AI threshold is deliberate: weak signals alone (for
example, no EXIF plus a smooth, vivid image) should land in
"uncertain", not in "likely AI-generated".

Limitations
-----------
* Metadata can be stripped, edited, or faked, so its absence or
  presence is weak evidence on its own.
* Many real photos have no EXIF (for example after being shared or
  re-saved), and many AI images can carry fake camera metadata.
* The image-statistics heuristics are deliberately lightweight and
  weak: smooth areas and high saturation also occur in real photos.
* No network calls, no model downloads, and no API keys are used.
  Nothing in this program is a definitive AI detector.

Usage
-----
    python ai_image_check.py <image_path> [--json]

Pillow is optional. If it is installed, simple image statistics are
included; if it is not, the program still runs on metadata and
format clues alone and says so in its output.
"""

from __future__ import annotations

import argparse
import json
import re
import struct
import sys
import zlib
from pathlib import Path

try:
    from PIL import Image  # type: ignore

    PILLOW_AVAILABLE = True
except Exception:  # Pillow is optional; degrade gracefully.
    Image = None  # type: ignore
    PILLOW_AVAILABLE = False


# ---------------------------------------------------------------------------
# Constants
# ---------------------------------------------------------------------------

GENERATOR_KEYWORDS = (
    "midjourney",
    "dall-e",
    "dall·e",
    "stable diffusion",
    "stable-diffusion",
    "adobe firefly",
    "firefly",
    "imagen",
    "flux",
    "ideogram",
    "leonardo",
    "runway",
    "sora",
    "gpt-image",
    "ai generated",
    "ai-generated",
    "generated by ai",
    "synthetic image",
    "c2pa",
    "content credentials",
)

CAMERA_MAKES = (
    "canon",
    "nikon",
    "sony",
    "fujifilm",
    "fuji",
    "olympus",
    "panasonic",
    "leica",
    "pentax",
    "gopro",
    "apple",
    "samsung",
    "google",
    "hasselblad",
    "ricoh",
)

SOFTWARE_KEYWORDS = (
    "adobe photoshop",
    "photoshop",
    "lightroom",
    "gimp",
    "paint.net",
    "affinity photo",
)

# File signatures: (magic bytes, format name). Keep this small and explicit.
FILE_SIGNATURES = (
    (b"\xff\xd8\xff", "JPEG"),
    (b"\x89PNG\r\n\x1a\n", "PNG"),
    (b"GIF87a", "GIF"),
    (b"GIF89a", "GIF"),
    (b"BM", "BMP"),
    (b"II*\x00", "TIFF"),
    (b"MM\x00*", "TIFF"),
    # WebP is RIFF....WEBP; checked separately because of the gap.
)


def detect_format(data: bytes) -> str | None:
    """Return a format name from magic bytes, or None if unrecognised."""
    for magic, name in FILE_SIGNATURES:
        if data.startswith(magic):
            return name
    if data[:4] == b"RIFF" and data[8:12] == b"WEBP":
        return "WEBP"
    return None


def extract_printable_text(data: bytes, max_len: int = 2_000_000) -> str:
    """Extract printable ASCII-ish strings from raw bytes.

    This is intentionally simple: it is only used to look for
    metadata keywords, not to parse EXIF/XMP fully. The result is
    lower-cased for keyword matching.
    """
    chunk = data[:max_len]
    # Replace non-printable bytes with a space, then collapse whitespace.
    text = "".join(chr(b) if 32 <= b < 127 else " " for b in chunk)
    text = re.sub(r"\s+", " ", text)
    return text.lower()


def extract_png_text_chunks(data: bytes) -> list[str]:
    """Return decoded PNG tEXt / iTXt / zTXt chunk contents, if any.

    Returns an empty list for non-PNG data or on any parse problem;
    a malformed PNG should not crash the checker.
    """
    chunks: list[str] = []
    if not data.startswith(b"\x89PNG\r\n\x1a\n"):
        return chunks
    pos = 8
    try:
        while pos + 8 <= len(data):
            length = struct.unpack(">I", data[pos : pos + 4])[0]
            chunk_type = data[pos + 4 : pos + 8].decode("ascii", "ignore")
            start = pos + 8
            end = start + length
            if end > len(data):
                break
            body = data[start:end]
            if chunk_type in ("tEXt", "iTXt"):
                chunks.append(body.decode("utf-8", "ignore"))
            elif chunk_type == "zTXt":
                # zTXt body: keyword, NUL, compression byte, compressed text.
                try:
                    nul = body.index(b"\x00")
                    chunks.append(
                        zlib.decompress(body[nul + 2 :]).decode(
                            "utf-8", "ignore"
                        )
                    )
                except Exception:
                    pass
            if chunk_type == "IEND":
                break
            pos = end + 4  # skip CRC
    except Exception:
        # Malformed PNG metadata: ignore it rather than failing.
        return chunks
    return chunks


def analyse_metadata(data: bytes, fmt: str) -> dict:
    """Heuristic 1 & 2: metadata and file/format clues.

    Returns a dict with the keywords found and a short description of
    what was (or was not) found. Nothing here is treated as proof.
    """
    raw_text = extract_printable_text(data)
    png_text = " ".join(extract_png_text_chunks(data)).lower() if fmt == "PNG" else ""
    searchable = f"{raw_text} {png_text}"

    generator_found = sorted({k for k in GENERATOR_KEYWORDS if k in searchable})
    camera_found = sorted({k for k in CAMERA_MAKES if k in searchable})
    software_found = sorted({k for k in SOFTWARE_KEYWORDS if k in searchable})

    # "C2PA" appears in the generator list, but call it out separately
    # because it is a provenance standard, not a generator name.
    has_c2pa = "c2pa" in searchable or "jumbf" in searchable

    # Very rough EXIF presence check: JPEG APP1 / "Exif" marker, or a
    # PNG eXIf chunk. Absence is common in shared images, so it is
    # only ever a weak signal (see scoring below).
    has_exif_marker = ("exif" in searchable) or (fmt == "PNG" and b"eXIf" in data)

    return {
        "format": fmt,
        "generator_keywords": generator_found,
        "camera_makes": camera_found,
        "software_keywords": software_found,
        "has_c2pa_marker": has_c2pa,
        "has_exif_marker": has_exif_marker,
        "png_text_chunks_found": len(extract_png_text_chunks(data))
        if fmt == "PNG"
        else 0,
    }


def analyse_image_statistics(path: Path) -> dict | None:
    """Heuristic 3: simple image statistics, Pillow only.

    Lightweight and deliberately weak: a small thumbnail is used, and
    only two summaries are computed.

    * mean neighbour difference: a proxy for texture/noise. Very low
      values mean large smooth areas, which can occur in AI images
      but also in real photos of sky, walls, or out-of-focus areas.
    * mean saturation: unusually high saturation can occur in
      AI images, but also in edited or vivid real photos.

    Returns None when Pillow is unavailable or the image cannot be
    opened (the caller then reports that statistics were skipped).
    """
    if not PILLOW_AVAILABLE or Image is None:
        return None
    try:
        with Image.open(path) as img:
            img = img.convert("RGB")
            # Work on a thumbnail so this stays fast on large files.
            thumb = img.copy()
            thumb.thumbnail((256, 256))
            width, height = thumb.size
            if width < 2 or height < 2:
                return None
            pixels = list(thumb.getdata())

            def pixel(x: int, y: int) -> tuple[int, int, int]:
                return pixels[y * width + x]

            neighbour_diffs: list[float] = []
            saturations: list[float] = []
            for y in range(height):
                for x in range(width):
                    r, g, b = pixel(x, y)
                    mx, mn = max(r, g, b), min(r, g, b)
                    saturations.append((mx - mn) / mx if mx else 0.0)
                    if x + 1 < width:
                        r2, g2, b2 = pixel(x + 1, y)
                        neighbour_diffs.append(
                            (abs(r - r2) + abs(g - g2) + abs(b - b2)) / 3.0
                        )
            if not neighbour_diffs:
                return None
            return {
                "mean_neighbour_difference": round(
                    sum(neighbour_diffs) / len(neighbour_diffs), 2
                ),
                "mean_saturation": round(
                    sum(saturations) / len(saturations), 3
                ),
                "thumbnail_size": [width, height],
            }
    except Exception:
        return None


def score_and_reasons(metadata: dict, stats: dict | None) -> tuple[int, list[str]]:
    """Combine heuristics into a 0-100 score and labelled reasons.

    Starts at 50 (uncertain) and adjusts by small, documented weights.
    Every reason is labelled as a heuristic, not proof.
    """
    score = 50
    reasons: list[str] = []

    if metadata["generator_keywords"]:
        score += 35
        reasons.append(
            "heuristic: metadata mentions an AI generator "
            f"({', '.join(metadata['generator_keywords'])})"
        )
    if metadata["has_c2pa_marker"]:
        score += 10
        reasons.append(
            "heuristic: file contains a C2PA / content-credentials marker "
            "(provenance metadata, not proof of AI generation on its own)"
        )
    if metadata["camera_makes"]:
        score -= 25
        reasons.append(
            "heuristic: metadata mentions a camera make "
            f"({', '.join(metadata['camera_makes'])})"
        )
    elif metadata["software_keywords"]:
        score += 10
        reasons.append(
            "heuristic: software-only provenance "
            f"({', '.join(metadata['software_keywords'])}) with no camera make found"
        )
    elif not metadata["has_exif_marker"]:
        score += 5
        reasons.append(
            "heuristic: no camera EXIF marker found "
            "(weak: many real shared photos also have no EXIF)"
        )

    if stats is None:
        if not PILLOW_AVAILABLE:
            reasons.append(
                "heuristic: image statistics skipped (Pillow not installed); "
                "verdict is based on metadata/format clues only"
            )
        else:
            reasons.append(
                "heuristic: image statistics skipped "
                "(image could not be analysed); verdict is based on "
                "metadata/format clues only"
            )
    else:
        diff = stats["mean_neighbour_difference"]
        sat = stats["mean_saturation"]
        if diff < 4.0:
            score += 10
            reasons.append(
                "heuristic: very smooth / low-noise areas "
                f"(mean neighbour difference {diff}; weak evidence, "
                "real photos of sky or plain surfaces look similar)"
            )
        elif diff > 25.0:
            score -= 5
            reasons.append(
                "heuristic: relatively textured / noisy image "
                f"(mean neighbour difference {diff}; weak evidence)"
            )
        if sat > 0.55:
            score += 5
            reasons.append(
                "heuristic: unusually high average saturation "
                f"({sat}; weak evidence, edited real photos can also be vivid)"
            )

    score = max(0, min(100, score))
    if not reasons:
        reasons.append("heuristic: no useful metadata or statistics signal found")
    return score, reasons


def verdict_for_score(score: int) -> str:
    """Map a 0-100 score to a plain-language, non-absolute verdict."""
    if score >= 75:
        return "likely AI-generated"
    if score <= 35:
        return "likely real / camera photo"
    return "uncertain"


def check_image(path: Path) -> dict:
    """Run all heuristics for one file and return a result dict.

    Raises ValueError with a clear, user-facing message (not a
    traceback) for missing files, non-images, and unsupported formats.
    """
    if not path.exists():
        raise ValueError(f"file not found: {path}")
    if not path.is_file():
        raise ValueError(f"not a regular file: {path}")

    try:
        data = path.read_bytes()
    except OSError as exc:
        raise ValueError(f"could not read file: {path} ({exc})") from exc

    if not data:
        raise ValueError(f"file is empty: {path}")

    fmt = detect_format(data)
    if fmt is None:
        # A text file (for example SVG source or a .txt renamed) is
        # not a supported raster image for this checker.
        raise ValueError(
            f"not a supported image file: {path} "
            "(supported: JPEG, PNG, GIF, WebP, BMP, TIFF)"
        )

    metadata = analyse_metadata(data, fmt)
    stats = analyse_image_statistics(path)
    score, reasons = score_and_reasons(metadata, stats)

    return {
        "path": str(path),
        "format": fmt,
        "verdict": verdict_for_score(score),
        "score": score,
        "reasons": reasons,
        "metadata": metadata,
        "image_statistics": stats,
        "pillow_available": PILLOW_AVAILABLE,
        "note": (
            "Heuristic result only, not proof. "
            "Metadata can be stripped or faked, and image statistics "
            "are weak evidence."
        ),
    }


def build_parser() -> argparse.ArgumentParser:
    """Build the CLI parser, including the limitations in --help."""
    parser = argparse.ArgumentParser(
        description=(
            "Check an image for heuristic signs of AI generation. "
            "This is NOT a definitive AI detector."
        ),
        epilog=(
            "Limitations: this program uses metadata, format clues, and "
            "simple image statistics only. Metadata can be stripped, "
            "edited, or faked, and smooth or vivid areas also occur in "
            "real photos. Treat every verdict as a labelled heuristic "
            "guess, not certainty, and do not use it as sole proof "
            "about an image's origin. No network calls are made."
        ),
    )
    parser.add_argument(
        "image_path",
        help="Path to an image file (JPEG, PNG, GIF, WebP, BMP, or TIFF).",
    )
    parser.add_argument(
        "--json",
        action="store_true",
        help="Print the result as JSON instead of human-readable text.",
    )
    return parser


def print_text_result(result: dict) -> None:
    """Print a short, human-readable result."""
    print(f"File:    {result['path']}")
    print(f"Format:  {result['format']}")
    print(f"Verdict: {result['verdict']}")
    print(f"Score:   {result['score']} / 100 (0 = likely real, 100 = likely AI)")
    print("Reasons:")
    for reason in result["reasons"]:
        print(f"  - {reason}")
    print(f"Note:    {result['note']}")


def main(argv: list[str] | None = None) -> int:
    """CLI entry point. Returns 0 on success, 2 on a handled error."""
    parser = build_parser()
    args = parser.parse_args(argv)

    try:
        result = check_image(Path(args.image_path))
    except ValueError as exc:
        print(f"Error: {exc}", file=sys.stderr)
        return 2

    if args.json:
        print(json.dumps(result, indent=2))
    else:
        print_text_result(result)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
