# Metadata is normally near the start of a file. For very large files
# we scan only the first chunk for raw text, so a huge image does not
# have to be held in memory twice. Structured parsers below work on
# the same scanned bytes; Pillow opens the file by path, not from
# these bytes, so statistics are unaffected.
METADATA_SCAN_LIMIT = 16 * 1024 * 1024

# Weak-signal cap: see module docstring.
WEAK_SIGNAL_CAP = 20


def detect_format(data: bytes) -> str | None:
    """Return a format name from magic bytes, or None if unrecognised."""
    for magic, name in FILE_SIGNATURES:
        if data.startswith(magic):
            return name
    if data[:4] == b"RIFF" and data[8:12] == b"WEBP":
        return "WEBP"
    return None


def extract_printable_text(data: bytes, max_len: int = 2_000_000) -> str:
    """Extract printable ASCII-ish strings from raw bytes.

    Only used as a fallback keyword scan, not as a substitute for the
    structured parsers below. The result is lower-cased for matching.
    """
    chunk = data[:max_len]
    text = "".join(chr(b) if 32 <= b < 127 else " " for b in chunk)
    text = re.sub(r"\s+", " ", text)
    return text.lower()


def _find_keywords(text: str, keywords) -> list[str]:
    """Return the sorted keywords present in ``text`` (already lower)."""
    return sorted({k for k in keywords if k in text})


